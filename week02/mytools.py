# mytools.py —— 第 12 天：我自己写的第一个"模块"
#
# 这个文件不直接运行，它是被 day12.py 用 from mytools import greet, half 拿走的。
# 判断一个 .py 是不是模块，只看一件事：里面的函数有没有被别人 import。
#
# 怎么验证它没写错：在 week02 里新建一个终端，输入
#   python -c "import mytools; print(mytools.greet('陈卓'))"
# 能打印出「你好，陈卓」就说明这个模块是好的。
# ============================================================

def greet(name):
    """打一声招呼：传进名字，返回一句问候。"""
    # f"..." 里 {name} 会被替换成传进来的参数
    return f"你好，{name}"

def half(n):
    """取一半：n / 2。注意 / 的结果永远是小数（float）—— half(10) 是 5.0。"""
    # 想要整数结果可以用 n // 2，但那样 5/2 会变成 2（丢掉小数）
    return n / 2

