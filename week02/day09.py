# "遍历" = 一个一个过一遍。这一天要掌握 for ... in 列表 的三种常见写法。
# ============================================================

jobs = ["后端开发", "数据分析", "算法工程师", "测试开发"]

# 最常用的写法：for 变量 in 列表，变量每轮等于列表里的一个元素。
for job in jobs:
    print("岗位：", job)

print("---")

# enumerate(列表, start=1) 同时给你"编号 + 元素"。
# 编号默认从 0 开始，写 start=1 就从 1 开始（人习惯从 1 数）。
# 这里用 i 接编号、job 接元素，两个变量用逗号隔开。
for i, job in enumerate(jobs, start=1):
    print(i, job)

# in 还能用来"判断一段文字里有没有某个词"。
# "数据" in "数据分析" 是真（True），所以这一条会打印出来。
for job in jobs:
    if "数据" in job:
        print("匹配到：", job)

# 小计数器：数一数有几个岗位名字里带"开发"。
counter = 0                       # 先准备一个计数器，从 0 开始
for job in jobs:
    if "开发" in job:
        counter = counter + 1     # 命中一次就 +1（等价于 counter += 1）
print("开发出现的次数:", counter)

# 这类"遍历 + 判断 + 累加"的三件套，就是后面数据分析最常用的骨架。
