# 花括号 {} + "键": 值 的形式就是字典
job = {
    "title": "后端开发工程师",
    "company": "某科技",
    "salary": "15-25K",
    "city": "深圳"
}

# 用键取值：job["title"] → "后端开发工程师"
print(job["title"])

# .get(键) 和 [] 的区别：键不存在时，[] 会直接报 KeyError 让程序崩掉；
# .get() 会安静地返回 None（不崩）。所以不确定有没有这个键时用 get。
print(job.get("city"))

# .get(键, 默认值)：键不存在就返回你给的默认值 → 这里打印"无"
print(job.get("bonus", "无"))

# 改一个已有的值：直接重新赋值即可
job["salary"] = "18-28K"

# 增加一个新键：键不存在就会被创建，值可以是任何东西，包括列表
job["tags"] = ["Java", "本科"]
print(job)

# .items() 同时拿出"键和值"，是遍历字典的标准写法。
# k 是键（title/company…），v 是值
for k, v in job.items():
    print(k, "=", v)

# ↓↓↓ 真实数据长这样：一个列表，每个元素是一个字典 ↓↓↓
jobs = [
    {"title": "后端开发", "city": "深圳", "salary": "15-25K"},
    {"title": "数据分析", "city": "深圳", "salary": "12-18K"},
    {"title": "算法工程师", "city": "北京", "salary": "25-40K"},
]

# 筛选：只要深圳的。j 是一整个字典，j["city"] 取出城市来比
for j in jobs:
    if j["city"] == "深圳":
        print(j["title"], j["salary"])

# split("-") 把字符串按 "-" 切开变成列表，[0] 取第一段 → "15k"
print("15-25K".split("-")[0])

# 组合技：先切出 "15"，再用 int() 转成数字 15，才能比较大小。
# 这是处理"薪资区间"这类字符串的标准做法。
for j in jobs:
    if int(j["salary"].split("-")[0]) >= 15:
        print(j["title"], j["salary"])

# 提醒：如果某条数据的 salary 是空的 ""，split 出来是 [""]，int("") 会报错。
