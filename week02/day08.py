# 列表就是"一排格子"，每个格子有编号（索引），从 0 开始数。
# ============================================================

# 方括号 [] 就是列表，元素之间用逗号隔开。
scores = [88, 92, 75, 60]

# scores[0]：取第 1 个格子（编号从 0 开始！）→ 88
print(scores[0])

# 编号 -1 表示"倒数第一个"，-2 是倒数第二 → 60
# 记住 -1 这个写法，取最后一个元素时特别常用
print(scores[-1])

# len() 数一数里面有几个元素 → 4
print(len(scores))

# max / min / sum 是现成的三个工具：最大值、最小值、总和
print(max(scores), min(scores), sum(scores))

# append() 往列表末尾"追加"一个元素；原来的 4 个变成 5 个
scores.append(99)
print(scores)

# sort() 就地把列表排序（默认从小到大）；
# reverse=True 表示倒序，也就是从大到小
scores.sort(reverse=True)
print(scores)

# 排完序后 scores = [99, 92, 88, 75, 60]，所以 [1] 是第二个 → 92
print(scores[1])

# 切片 scores[1:4]：从编号 1 取到编号 4，但"含头不含尾"→ 取 1、2、3 三个
# 结果 [92, 88, 75]；注意 4 这个位置本身不包含在内
print(scores[1:4])
