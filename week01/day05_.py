age = input("你的年龄是：")

# input 拿到的是文字 "25"，必须转成数字 25，否则下面 age >= 60 会报错。
# 试着把这行注释掉再跑一次，看看报什么错 —— 那个错就是 TypeError。
age = int(age)

# 从大到小判断：先问是不是 >= 60，不成立再问是不是 >= 18。
# 如果顺序反过来（先问 >= 18），60 岁的人会先被"成年"抓住，永远走到"老年"。
if age >= 60:
    print("老年")
elif age >= 18:
    print("成年")
else:
    print("未成年")
