# range(5) 生成 0,1,2,3,4 —— 注意：从 0 开始，不含 5。
# 每次循环，i 依次等于其中一个数，然后执行下面缩进的 print(i)。
for i in range(5):
    print(i)

print("---")

# 小累加器：先准备一个"空箱子"，从 0 开始。
total = 0

# range(1, 101) 是 1 到 100（含 1、不含 101）—— 求 1~100 别忘了写 101。
for i in range(1, 101):
    # i % 2 == 0 就是"能被 2 整除"，也就是偶数
    if i % 2 == 0:
        # total = total + i 可以简写成 total += i，两个一样
        total = total + i

# 循环结束后，total 已经是 1~100 里所有偶数的和（结果是 2550）
print(total)

print("---")

# while：条件为真就一直转，直到条件变假。
# 这里 n 从 3 开始，每转一圈减 1，减到 0 就不满足 n > 0，循环结束。
n = 3
while n > 0:
    print(n)
    n = n - 1        # 这行千万不能忘！忘了写就是死循环，只能按 Ctrl+C 停。

print("起飞")

