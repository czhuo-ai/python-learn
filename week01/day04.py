# input("提示语")：先把提示语显示出来，然后等你打字 + 回车。
# 你打的字会被当成「字符串」，存进变量 name 里。
name = input("你叫什么名字？")

# 同样，这里拿到的 year 是字符串，比如 "2004"，不是数字 2004。
birth = input("你是哪一年出生的")

# 这一步不能省：把字符串 "2004" 转成整数 2004。
# 不转的话，下面 2026 - birth 会报 TypeError（文字不能和数字相减）。
birth = int(birth)

# 现在 birth 是整数了，减法才有意义。变量 age 存下这个结果。
age = 2026 - birth

# f"..." 叫 f-string：字符串前面加 f，里面用 {变量名} 就能把变量的值塞进去。
print(f"你好，{name}")
print(f"你好，你今年大概{age}岁")

