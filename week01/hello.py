# print("...")：引号里的东西叫「字符串」，会原样打印到屏幕上。
# 注意：中文的引号 “” 不行，必须用英文的 " 或 '
print("你好，我是陈卓")
print("今天开始学python")

# 不加引号的 1+2 是「算术」：电脑先算，再把结果 3 打印出来。
print(1+2)

# 加了引号的 "1+2" 是「文字」：电脑不算，原样打印 1+2。
# 这两行的区别，就是「数据」和「文字」的区别 —— 后面天天要用。
print("1+2")
