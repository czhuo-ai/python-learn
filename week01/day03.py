# 这是一行注释：以 # 开头，电脑整行跳过，只写给人看。
# 写注释不是"写给老师"，是写给三个月后的自己 —— 那时你会忘。

print("第一行")
print("第二行")

# 减法：2026 - 2004 = 22（不带引号才会算）
print(2026-2004)

# / 是真除法：10 ÷ 4 = 2.5，结果是小数（float）
print(10/4)

# // 是整除：只保留整数部分，10 ÷ 4 = 2（小数被直接丢掉，不是四舍五入）
print(10//4)

# % 是取余数：10 ÷ 4 商 2 余 2，所以结果是 2
# 判断奇偶就靠它：n % 2 == 0 就是偶数
print(10%4)

# 字符串也能做乘法："---" 乘 10 = 连着 30 个减号，常用来画分隔线
print("---"*10)

# 整除也可以拿来做"取千位"这种操作：2026 // 1000 = 2
print(2026//1000)
