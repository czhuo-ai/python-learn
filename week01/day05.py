# 怎么跑：python day05.py，然后输一个分数（比如 95）回车
# 这一天只练一件事：让程序"分情况做事"。
# ============================================================

score = input("你的分数是：")

# 和昨天一样：input 给的是文字，要比较大小必须先转成整数。
score = int(score)

# if 后面的条件为真（True），就执行它下面缩进的那几行。
# 注意 == 是两个等号，意思是"判断是否相等"；一个 = 是"赋值"。
if score == 100:
    print("满分")

# elif = else if：上面的条件不成立，再看这一条。
# 顺序很重要：90 分以上先被上面挡掉，所以这里只剩 90~99。
elif score >= 90:
    print("优秀")

# 同理，走到这里说明分数不到 90，那 >= 60 就是 60~89。
elif score >= 60:
    print("及格")

# else：上面的条件全都不成立时，走这里（也就是 60 分以下）。
else:
    print("不及格")

# 缩进（行首那 4 个空格）不是排版，是语法：
# 它决定了哪几行"属于"上面那个 if。少一个空格就会报 IndentationError。
print("程序结束")
